// Правило ботов (решение владельца): боты — только когда в заезде или матче ровно один человек.
// Двое и больше — ботов нет совсем. Общее для сервера (картинг, регата, пейнтбол, Fight Club) и клиента
// (таблички и подсказки говорят то же самое).

/** Нужны ли боты, если в заезде или матче столько людей: только соло. */
export function botsAllowed(humans: number): boolean {
  return humans === 1;
}

/** Правило одной фразой — для табличек и подсказок. */
export const BOTS_RULE = 'боты — только соло';

/** «с ботами» или «без ботов» для такого числа людей (0 — пока никого, тогда правило). */
export function botsWord(humans: number): string {
  return humans <= 0 ? BOTS_RULE : botsAllowed(humans) ? 'с ботами' : 'без ботов';
}
