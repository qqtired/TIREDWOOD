// v2: exact triangles provide support; only visible physical structures need AABB obstacles.
import fs from 'node:fs';
import path from 'node:path';
import { scene } from './glb.mjs';
const ROOT = path.resolve(import.meta.dirname, '../..');
const floors = [[55, -1.2, -11.2, 61.3, 1.8, -5.8]];
const solids = [
  [28.6, -3, -32.2, 35.4, 30, -23.1], [3.3, -3, -2, 13.3, 30, 6], [20.6, -3, -13.9, 29.4, 30, -4.6],
  [24.9, -3, 8.4, 34.5, 30, 15.6], [6.5, -3, -40.8, 18.4, 30, -28.8], [46.5, -3, -20.2, 53.4, 30, -12],
  [71.6, -3, -63.4, 78.4, 45, -56.6], [77.6, -3, -59, 84.6, 30, -53], [54.1, -3, -16.8, 54.85, 5, -16],
  [55.1, -3, -11.1, 56.8, 4, -9.3], [55.4, -3, -7.2, 57.4, 4, -6], [58.2, -3, -7.1, 59.9, 4, -6.1], [59.6, -3, -12.2, 60.9, 5, -10.6],
  [118.52, 2.28, 12.72, 119.81, 6.7, 14.01],
];
const walls = [];
const lighthouse = await scene(path.join(ROOT, 'client/assets/isle/lighthouse.glb'));
const run = Math.hypot(12, -28), sx = 28 / run, sz = 12 / run;
const terrain = await scene(path.join(ROOT, 'client/assets/isle/island-terrain.glb'));
const { heights, triangles } = await import('./glb.mjs');
const foot = heights(triangles(terrain, (o) => o.name === 'terrain'))(56, -22) + 0.03;
for (const side of [-1, 1]) for (let i = 0; i <= 13; i++) {
  const t = i / 13, x = 56 + 12 * t + sx * side * 1.28, z = -22 - 28 * t + sz * side * 1.28, h = foot + (16 - foot) * t;
  walls.push([x - 0.07, h - 0.18, z - 0.07, x + 0.07, h + 1.05, z + 0.07]);
}
// AABB segments follow the real diagonal handrail in 0.29m pieces. Long boxes would cut across the stair lane.
for (const side of [-1, 1]) for (let i = 0; i < 104; i++) {
  const t0 = i / 104, t1 = (i + 1) / 104;
  const ax = 56 + 12 * t0 + sx * side * 1.28, az = -22 - 28 * t0 + sz * side * 1.28;
  const bx = 56 + 12 * t1 + sx * side * 1.28, bz = -22 - 28 * t1 + sz * side * 1.28;
  walls.push([Math.min(ax, bx) - 0.045, foot + (16 - foot) * t0 + 0.975, Math.min(az, bz) - 0.045,
    Math.max(ax, bx) + 0.045, foot + (16 - foot) * t1 + 1.065, Math.max(az, bz) + 0.045]);
}
lighthouse.traverse((o) => {
  if (!o.isMesh || o.material.name !== 'fi_stone' || !/^lighthouse/.test(o.name)) return;
  const p = o.geometry.getAttribute('position'), idx = o.geometry.index, cells = new Map();
  for (let i = 0; i < (idx?.count ?? p.count); i += 3) {
    const a = [0, 1, 2].map((k) => { const n = idx ? idx.getX(i + k) : i + k; return [p.getX(n), p.getY(n), p.getZ(n)]; });
    const cx = a.reduce((s, q) => s + q[0], 0) / 3, cz = a.reduce((s, q) => s + q[2], 0) / 3, r = Math.hypot(cx - 75, cz + 60);
    if (r < 9.5 || r > 11) continue;
    const key = Math.round(Math.atan2(cz + 60, cx - 75) / (2 * Math.PI / 22));
    const b = cells.get(key) ?? [Infinity, Infinity, Infinity, -Infinity, -Infinity, -Infinity];
    for (const q of a) for (let k = 0; k < 3; k++) { b[k] = Math.min(b[k], q[k]); b[k + 3] = Math.max(b[k + 3], q[k]); }
    cells.set(key, b);
  }
  for (const b of cells.values()) if (b[4] - b[1] > 0.25 && b[3] - b[0] > 0.05 && b[5] - b[2] > 0.05) walls.push(b.slice(0, 6));
});
const fmt = (x) => JSON.stringify(x.map((n) => Math.round(n * 10000) / 10000));
const field = (name, a) => `export const ${name}: ReadonlyArray<readonly [number, number, number, number, number, number]> = [\n${a.map((b) => '  ' + fmt(b)).join(',\n')}\n];\n`;
fs.writeFileSync(path.join(ROOT, 'shared/maps/isleboxes.ts'), '// Generated by tools/isle/collision.mjs. v2 exact support is in isleterrain-data.ts; no synthetic cliff floors/walls.\n' + field('ISLE_FLOORS', floors) + field('ISLE_WALLS', walls) + field('ISLE_SOLIDS', solids));
console.log(JSON.stringify({ floors: floors.length, walls: walls.length, solids: solids.length }));
