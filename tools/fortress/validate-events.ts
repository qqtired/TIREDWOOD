import assert from 'node:assert/strict';
import * as THREE from 'three';
import { EventFx } from '../../client/fort/eventfx.ts';
import { EventMarks } from '../../client/fort/marks.ts';
const scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera();camera.position.set(0,5,15);
const fx=new EventFx(scene,camera);
fx.siegeMeteor(1000001,0,[0,10,0],[0,0,0],0,120,0);
assert(Math.abs(fx.meteorRay(0,10,10,0,0,-1,100)!-8.2)<1e-6);
assert.equal(fx.meteorRay(0,10,10,0,0,-1,5),null,'nearer world surface must win');
fx.setRenderTick(30);fx.update(.1);
assert(Math.abs(fx.meteorRay(0,7.5,10,0,0,-1,100)!-8.2)<1e-6,'linear motion must match drawn sphere');
fx.siegeMeteor(1000001,1,[0,10,0],[0,0,0],0,120,30);
assert.notEqual(fx.meteorRay(0,7.5,10,0,0,-1,100),null,'nonlethal hit keeps the target');
fx.siegeMeteor(1000001,2,[0,10,0],[0,0,0],0,120,30);
assert.equal(fx.meteorRay(0,7.5,10,0,0,-1,100),null,'shotdown removes target immediately');
const markerScene=new THREE.Scene(),marks=new EventMarks(markerScene);
marks.meteor(0,0,0,5,100,100,1000001);marks.cancel(1000001);marks.update(.01,1);
const batches=markerScene.children.filter(o=>(o as THREE.InstancedMesh).isInstancedMesh) as THREE.InstancedMesh[];
assert.equal(batches.reduce((n,m)=>n+m.count,0),0,'shotdown removes every target marker');
marks.meteor(0,0,0,3,100,100);marks.meteor(10,0,0,3,100,100);marks.update(.01,1);
assert.equal(batches[0].count,2,'legacy untargetable meteors keep independent marks');
marks.clear();marks.stripe(24,1,4,2,8,3.2,100,100);marks.update(.01,1);
assert.equal(batches[0].count,0);assert.equal(batches[2].count,1,'wind uses rectangular marker');
console.log(JSON.stringify({pass:true,checks:8,meteorRadius:1.8,exactLinear:true,airburstCancellation:true,legacyMarks:true,windStripe:true}));
