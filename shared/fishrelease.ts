// После поимки (рыбалка 2.0): рыба в руках — выбор, последовательный (хотфикс 10.10): сперва выбираешь, потом забрасываешь.
// Кнопка «В рюкзак» (или клавиша 1) — рыба остаётся в рюкзаке по цене поимки; кнопка «Отпустить» (или F, или 2) — обратно
// в воду: жетонов нет, в рюкзак не идёт, опыт рыбалки за поимку ×1,5. Пока выбор не сделан, ЛКМ и пробел не забрасывают
// (ни клиент, ни сервер), а первые CHOICE_LOCK_MS после конца вываживания не принимаются никакие нажатия — иначе ЛКМ,
// которым тянули рыбу, сразу выбирал и забрасывал. Выбрал — ЛКМ снова забрасывает. Альбом, рекорды, доска и задание Семёна
// засчитаны в момент поимки — её же поймали. Не выбрал за CHOICE_TICKS — рыба остаётся в рюкзаке. Рюкзак полон —
// заброс не уходит (BAG_FULL_HINT).
// Сервер: server/lobby/fishing2.ts (release, land); клиент: client/lobby/fishcard2.ts (кнопки), fish2hud.ts (пауза), scene.ts (клавиши).
import { TICK_RATE } from './constants.ts';

/** После конца вываживания (поймал, сорвалась, сдался) столько мс игнорируются все нажатия: ЛКМ, пробел, кнопки и клавиши выбора */
export const CHOICE_LOCK_MS = 750;

/** Опыт рыбалки за отпущенную рыбу: ×1,5 к опыту за поимку (отдельный множитель поверх базы и оценки вываживания) */
export const RELEASE_XP = 1.5;
/** Сколько рыба в руках ждёт выбора, тиков (сундук и хлам — как раньше, HOLD2_TICKS) */
export const CHOICE_TICKS = 7 * TICK_RATE;
/** FE_DONE: a — рыбу отпустили в воду (1 — в рюкзак/альбом, 0 — продал, 2 — в ведро у рыбаков-соседей) */
export const DONE_RELEASE = 3;
/** Подпись под кнопкой «Отпустить» */
export const RELEASE_NOTE = '+50 % опыта · без жетонов';
/** Подсказка, когда рюкзак полон (заброс не уходит): продать или отпустить рыбу из рюкзака — окно на I */
export const BAG_FULL_HINT = 'Рюкзак полон — продай улов Семёну или Сане или отпусти рыбу из рюкзака (I)';

/** Опыт рыбалки за поимку, если рыбу отпустили (xp — за поимку с оценкой вываживания) */
export function releaseXp(xp: number): number {
  return Math.round(Math.max(0, xp) * RELEASE_XP);
}
