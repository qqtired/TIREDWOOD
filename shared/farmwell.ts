// Ферма: мини-игра «Набери лейку» (design-v11 §7). Сервер переигрывает ту же одномерную модель со своим зерном по
// отсчётам клиента (x ведра, наклон — 30 в секунду) и сам считает долю заполнения. Владелец файла — часть B4.
// Пока модели нет: любая попытка даёт столько, сколько стоящий без движения (AFK, ~30 %).

/** Сколько отсчётов принимаем максимум: 10 с налива × 30/с, пары (x, наклон) */
export const WELL_MAX_SAMPLES = 10 * 30 * 2;
/** Доля без движения мышью (§7.1: «Зажал и не двигал мышь — 25–35 %») */
export const WELL_AFK_SHARE = 0.3;

/** Доля лейки 0–1 по зерну попытки и отсчётам клиента. Заглушка до модели B4. */
export function wellShare(_seed: number, samples: readonly number[]): number {
  return samples.length > 0 ? WELL_AFK_SHARE : 0;
}
