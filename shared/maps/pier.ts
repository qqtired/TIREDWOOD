// Карта «Причал»: бетонный пирс на закате, вокруг море.
// Карта центрально-симметрична: половина за «Мандарин» — это половина «Черники», повёрнутая на 180°.

import { Builder } from './builder.ts';
import type { GameMap } from './types.ts';

const PIER_HALF_X = 22;
const PIER_HALF_Z = 38;

export function buildPier(): GameMap {
  const b = new Builder();
  const X = PIER_HALF_X;
  const Z = PIER_HALF_Z;

  // --- Настил пирса и бордюр по краю
  b.box([-X, -0.6, -Z - 12], [X, 0, Z + 12], 'deck', 0xa39b8e);
  b.sym([X - 0.35, 0, -Z], [X, 0.22, Z], 'concrete', 0xd8d1c2);

  // Невидимые стены далеко в воде: чтобы рывком не улететь за горизонт
  b.sym([X + 5, -6, -Z - 12], [X + 6, 30, Z + 12], 'invisible', 0);
  // Небо-потолок не нужен: батуты не добрасывают выше 7 м

  // --- Склады на торцах (стена, в которую упирается арена)
  b.sym([-X - 2, 0, -Z - 1.2], [X + 2, 9, -Z], 'brick', 0xa0654f);
  // Ворота склада — чуть выступающие рамы (просто для рельефа, упираться можно)
  b.sym([-9, 0, -Z], [-3, 5.2, -Z + 0.25], 'metal', 0x6f7c83);
  b.sym([3, 0, -Z], [9, 5.2, -Z + 0.25], 'metal', 0x6f7c83);

  // --- Спавн «Черники» (z ≈ -35), смотрят в +Z (yaw = PI)
  const spawnRows: Array<[number, number]> = [
    [-10.5, -35.5], [-6.5, -34.2], [-2, -35.8], [2, -34.4],
    [6.5, -35.6], [10.5, -34.3], [-14.5, -34.8], [14.5, -35.2],
  ];
  for (const [x, z] of spawnRows) b.spawn(x, z, Math.PI);

  // Отбойники перед спавном: закрывают прострел в базу
  b.barrier(-6.5, -30.2, 'x', 4.2);
  b.barrier(6.5, -30.2, 'x', 4.2);
  b.barrier(0, -27.4, 'x', 3.0, 1.0);

  // Штабеля поддонов/ящиков у спавна
  b.crate(-17.5, 0, -33.5, 1.3);
  b.crate(-17.5, 1.3, -33.5, 1.3);
  b.crate(-16.1, 0, -32.3, 1.2);
  b.crate(17.8, 0, -31.5, 1.4);

  // --- Западный коридор (x < -12): длинный контейнер вдоль пирса + лестница на крышу
  b.container(-14.2, -20.5, 'z', 12, 0);
  b.stairs(-14.2, -30.2, '+z', 2.2, 2.6, 7, 0.52); // упирается в торец контейнера (z = -26.5)
  b.crate(-19.4, 0, -22.5, 1.25);
  b.crate(-19.6, 0, -15.5, 1.1);

  // --- Восточный край: высокая стопка контейнеров — ориентир и укрытие
  b.container(15.2, -23, 'z', 6, 0);
  b.container(15.2, -23, 'z', 6, 1);
  b.crate(12.6, 0, -18.6, 1.3);
  b.crate(12.6, 1.3, -18.6, 1.1);
  b.barrier(18.8, -14.5, 'z', 3.4);

  // --- Середина своей половины: поперечный контейнер и ящики
  b.container(4.5, -16.2, 'x', 6, 0);
  b.crate(-4.2, 0, -20.6, 1.3);
  b.crate(-5.6, 0, -19.4, 1.0);
  b.barrier(-7.5, -11.5, 'x', 3.2);
  b.crate(8.2, 0, -9.8, 1.25);
  b.crate(9.6, 0, -8.6, 1.0);

  // Контейнеры ближе к центру по бокам
  b.container(-15.6, -5.2, 'z', 6, 0);
  b.container(13.9, -8.4, 'x', 6, 0);

  // --- Центр: крест из двух контейнеров, верх (5.2 м) — царь горы
  b.container(0, 0, 'x', 12, 0, false, 0x3f6f8f);
  b.container(0, 0, 'z', 6, 1, false, 0x9a4a3a);
  // Под свесами верхнего контейнера — ящики-опоры (чтобы под крышей не было «второго этажа»)
  for (const x of [-0.61, 0.61]) {
    b.crate(x, 0, 1.83, 1.22);
    b.crate(x, 1.22, 1.83, 1.22);
  }
  // Ящики-ступеньки на первый ярус центра
  b.crate(-7.4, 0, -2.1, 1.25);
  b.crate(-8.7, 0, -3.3, 1.0);

  // Батуты: к кресту и к стопке
  b.trampoline(-2.8, -5.2);
  b.trampoline(17.0, -18.6);

  // --- Банки варенья: на краю у воды (рискованно) и на верху креста — в сторонке, посередине лежит AWP
  b.pickup(-19.8, 0, -9.5);
  b.pickup(0, 5.2, 2.2, false);

  // --- Декор (у кнехтов, фонарей и бочек есть невидимая коллизия)
  for (let z = -Z + 4; z <= Z - 4; z += 8) b.bollard(X - 0.9, z + 0.5);
  for (let z = -Z - 10; z <= Z + 10; z += 5) {
    b.deco.push({ kind: 'piling', x: X + 0.25, z });
    b.deco.push({ kind: 'piling', x: -X - 0.25, z: -z });
  }
  b.deco.push({ kind: 'rope', x: X - 1.6, z: -12.5, yaw: 0.3 });
  b.deco.push({ kind: 'rope', x: -X + 1.6, z: 12.5, yaw: 3.4 });
  b.deco.push({ kind: 'rope', x: -X + 1.5, z: -28, yaw: 1.2 });
  b.deco.push({ kind: 'rope', x: X - 1.5, z: 28, yaw: 4.3 });
  b.lamp(-11, -26);
  b.lamp(-19.5, -1);
  b.lamp(10.5, -28.5);
  b.barrel(-12.3, -31.8, 0x2f6a8a);
  b.barrel(-11.6, -32.6, 0x2f6a8a);
  b.barrel(18.9, -6.4, 0xb04a36);
  // портальные краны стоят на терминале за проливом, стрелы — над водой к пирсу
  b.deco.push({ kind: 'crane', x: 56, z: -34, yaw: Math.PI / 2, scale: 1 });
  b.deco.push({ kind: 'crane', x: 56, z: 22, yaw: Math.PI / 2, scale: 1.05 });
  b.deco.push({ kind: 'buoy', x: 31, z: -6, color: 0xe0492f });
  b.deco.push({ kind: 'buoy', x: -34, z: 14, color: 0xf2c230 });
  b.deco.push({ kind: 'buoy', x: 37, z: 30, color: 0xf2c230 });
  b.deco.push({ kind: 'boat', x: 33, z: 18, yaw: 0.4, color: 0xe8e2d4 });
  b.deco.push({ kind: 'boat', x: -36, z: -20, yaw: 2.6, color: 0x5d8fb0 });

  return {
    name: 'Причал',
    boxes: b.boxes,
    spawns: b.spawns,
    trampolines: b.trampolines,
    pickups: b.pickups,
    // снайперская AWP — посередине верха креста (царь горы), видна с обеих баз
    awp: { x: 0, y: 5.2, z: 0 },
    deco: b.deco,
    bounds: { minX: -X, maxX: X, minZ: -Z, maxZ: Z },
  };
}
