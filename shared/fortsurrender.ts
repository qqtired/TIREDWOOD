// Белый флаг крепости: «сдаться» голосованием. Общее для сервера (server/fort/surrender.ts) и клиента
// (client/fort/ui/surrender.ts): сроки, сколько «за» нужно и вид сообщения {t:'fsurr'}. Всё решает сервер: клиент только
// показывает состояние и шлёт {t:'fortVote', yes}. От числа волн в игре ничего не зависит.
import { TICK_RATE } from './constants.ts';

/** Голосование длится 20 с */
export const SURR_VOTE_TICKS = 20 * TICK_RATE;
/** После неудачи сдаться нельзя 45 с — всем сразу */
export const SURR_COOLDOWN_TICKS = 45 * TICK_RATE;
/** Первое E у флага ждёт второго 3 с («Сдаться? Нажми E ещё раз») */
export const SURR_ASK_TICKS = 3 * TICK_RATE;

/** Сколько «за» нужно из n голосующих — строго больше половины: 1→1, 2→2, 3→2, 4→3, 5→3, 6→4 */
export function surrenderNeed(n: number): number {
  return Math.floor(n / 2) + 1;
}

/**
 * Состояние голосования, как его видит клиент ({t:'fsurr'}; шлётся всем в крепости при каждом изменении, а вошедшему —
 * при входе). Номера — защитников в снимках (FortPlayerRow.id).
 */
export interface FortSurrender {
  /** Голосование идёт */
  open: boolean;
  /** Кто предложил (номер и имя — вышел, а имя осталось) */
  by: number;
  name: string;
  /** Кто голосует (все люди в крепости на начало, без ушедших), кто сказал «за», кто «против» */
  voters: number[];
  yes: number[];
  no: number[];
  /** Сколько «за» нужно сейчас (строго больше половины голосующих) */
  need: number;
  /** Тик, когда голосование кончится сам */
  end: number;
  /** Тик, до которого сдаться нельзя (после неудачи; 0 — можно) */
  cd: number;
  /** Только в сообщении, которым голосование закрылось неудачей: счёт — в yes/no/need */
  fail?: boolean;
  /** Только тому, кто нажал E первый раз: до какого тика нажать E ещё раз */
  ask?: number;
}
