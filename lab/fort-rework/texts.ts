const VNAME: Record<string, string> = { keep: 'оставить', polish: 'доработать', redo: 'переделать' };

export function renderSummary(el: HTMLElement): void {
  const n = { keep: 0, polish: 0, redo: 0 };
  for (const m of MOBS) n[m.verdict]++;
  const byCode = new Map<string, string[]>();
  for (const m of MOBS) if (m.code) byCode.set(m.code, [...(byCode.get(m.code) ?? []), m.name]);
  const num = (c: string) => Number(c.replace(/\D/g, ''));
  const codeIds = [...byCode.keys()].sort((a, b) => num(a) - num(b));
  const codes = codeIds.map((c) => `${c} ${byCode.get(c)!.join(' и ')}`).join(', ');
  const lastCode = codeIds[codeIds.length - 1] ?? 'М-1';
  const redo = MOBS.filter((m) => m.verdict === 'redo').map((m) => m.name).join(', ');
  el.innerHTML = `
    <div class="fr-card"><p class="k-eyebrow">Что не так сейчас</p>
      <p><b>Забег — 100 волн, больше двух часов,</b> а всё новое кончается на 45-й. Дальше — те же боссы со значком «II».</p>
      <p>Осадных врагов (12.10) делал Codex: <b>ноги скользят</b> (шаг в модели вдвое короче, чем в игре), у части поз <b>нет движения вовсе</b>, у башни и батареи «готовит удар» двигает только расчёт. У армии Барона (03.10) — хорошие модели, но три жеста не доходят до игры.</p>
    </div>
    <div class="fr-card"><p class="k-eyebrow">Что предлагаю</p>
      <p><b>Ф50-1</b> — 50 волн за час, пять глав, каждый босс один раз, летающий на 35-й и новый финальный на 50-й.</p>
      <p><b>С-1</b> — ломаемые стены: 11 участков, пролом, ремонт <b>E</b> + золото. Оформление пролома — <b>С-2а</b>.</p>
      <p>Мобы: ${MOBS.length} моделей — оставить ${n.keep}, доработать ${n.polish}, переделать ${n.redo}${redo ? ` (${redo})` : ''}.</p>
      <p>Механики: <b>К-1</b> камни со стены, <b>К-3</b> требушет, <b>К-6</b> выбор волны.</p>
    </div>
    <div class="fr-card"><p class="k-eyebrow">Что нужно от тебя</p>
      <p>Ответь кодами: <b>«делаем Ф50-1, С-1, С-2а, К-1, К-3, К-6 и М-1–${lastCode}»</b> или «бери ★». Карточки нажимаются — список соберётся внизу, кнопка «Скопировать».</p>
      <p>Новых боссов выбираешь на их странице — она встроена ниже, в разделе «Новые боссы».</p>
      <p class="fr-note">Коды мобов: ${codes || '—'}. Вердикты: ${Object.entries(n).map(([k, v]) => `${VNAME[k]} ${v}`).join(' · ')}.</p>
    </div>`;
}

