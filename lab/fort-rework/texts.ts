export function renderIdeas(el: HTMLElement): void {
  for (const idea of IDEAS) {
    const card = document.createElement('div');
    card.className = 'fr-var';
    card.dataset.pick = idea.id;
    card.innerHTML = `<div class="fr-var-top"><span class="id">${idea.id}</span>${idea.star ? '<span class="star">★ советую</span>' : ''}<span class="cost">цена <b>${idea.cost}</b></span></div><h4>${idea.title}</h4><p>${idea.what}</p><p><b>Почему весело:</b> ${idea.why}</p><p class="fr-note">${idea.how}</p>`;
    card.append(takeButton(idea.id, 'Беру'));
    card.addEventListener('click', () => card.querySelector<HTMLButtonElement>('.fr-take')!.click());
    el.append(card);
  }
}

