// ---- идеи и выбор «Беру»
const KEY = 'rakushka-next-pick';
const REC = GROUPS.flatMap(g => g.ideas.filter(i => i.rec).map(i => i.id));
const ORDER = GROUPS.flatMap(g => g.ideas.map(i => i.id));
let pick = new Set(REC);
try {
  const saved = JSON.parse(localStorage.getItem(KEY) || 'null');
  if (Array.isArray(saved)) pick = new Set(saved.filter(id => ORDER.includes(id)));
} catch { /* без хранилища — рекомендованное */ }

const cards = new Map();
const groups = document.getElementById('groups');
for (const g of GROUPS) {
  const box = el('div', 'nx-group');
  const h = el('h3', 'nx-group-h');
  h.append(el('b', 'nx-group-id', g.id), el('span', '', g.t));
  box.append(h);
  if (g.n) box.append(el('p', 'nx-group-n', g.n));
  const grid = el('div', 'nx-ideas');
  for (const it of g.ideas) {
    const c = el('button', 'nx-idea');
    c.type = 'button';
    const top = el('span', 'nx-idea-top');
    top.append(el('b', 'nx-id', it.id));
    if (it.m) top.append(el('span', 'k-pill k-pill--sm', it.m));
    if (it.rec) top.append(el('span', 'k-pill k-pill--sm k-pill--gold', 'рекомендую'));
    if (it.ask) top.append(el('span', 'k-pill k-pill--sm k-pill--special', 'реши ты'));
    top.append(el('span', 'nx-h', it.h));
    const take = el('span', 'nx-take');
    take.append(el('span', 'nx-check'), el('span', 'nx-take-l', 'Беру'));
    c.append(top, el('span', 'nx-idea-t', it.t), el('span', 'nx-idea-d', it.d), take);
    c.addEventListener('click', () => {
      if (pick.has(it.id)) pick.delete(it.id); else pick.add(it.id);
      sync();
    });
    cards.set(it.id, c);
    grid.append(c);
  }
  box.append(grid);
  groups.append(box);
}

const listText = () => ORDER.filter(id => pick.has(id)).join(', ');
function sync() {
  for (const [id, c] of cards) {
    const on = pick.has(id);
    c.classList.toggle('is-on', on);
    c.setAttribute('aria-pressed', String(on));
  }
  document.getElementById('pickN').textContent = String(pick.size);
  document.getElementById('pickList').textContent = listText() || 'ничего';
  try { localStorage.setItem(KEY, JSON.stringify([...pick])); } catch { /* не страшно */ }
}
sync();

document.getElementById('pickReset').addEventListener('click', () => {
  pick = new Set(REC);
  sync();
});
const copyBtn = document.getElementById('pickCopy');
copyBtn.addEventListener('click', async () => {
  const text = `«Ракушка», беру: ${listText() || 'ничего'}`;
  let ok = false;
  try { await navigator.clipboard.writeText(text); ok = true; } catch { /* ниже — запасной путь */ }
  if (!ok) {
    const t = el('textarea');
    t.value = text;
    document.body.append(t);
    t.select();
    try { ok = document.execCommand('copy'); } catch { ok = false; }
    t.remove();
  }
  copyBtn.textContent = ok ? 'Скопировано' : 'Не вышло — выдели список';
  setTimeout(() => { copyBtn.textContent = 'Скопировать'; }, 1600);
});
