const el = (tag, cls, text) => {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text != null) e.textContent = text;
  return e;
};
const ALL = SECTIONS.flatMap(s => s.ideas.map(i => ({ ...i, sec: s.id })));
const TAIL_ROWS = TAILS.flatMap(g => g.rows.map(r => ({ ...r, rel: g.rel })));
const ORDER = [...ALL.map(i => i.id), ...TAIL_ROWS.map(r => r.id)];
const REC = [...ALL.filter(i => i.rec).map(i => i.id), ...TAIL_ROWS.filter(r => r.rel).map(r => r.id)];
const nodes = new Map(); // id → [элементы, которые отмечаются «Беру»]
const addNode = (id, n) => { if (!nodes.has(id)) nodes.set(id, []); nodes.get(id).push(n); };

function costBadge(c) {
  const b = el('span', 'ix-cost');
  b.append(el('b', '', c), document.createTextNode(` · ${COST[c]}`));
  return b;
}

function ideaCard(it) {
  const c = el('button', 'ix-idea');
  c.type = 'button';
  c.dataset.id = it.id;
  c.dataset.sec = it.sec;
  c.dataset.cost = it.c;
  c.id = `idea-${ALL.indexOf(ALL.find(a => a.id === it.id))}`;
  const top = el('span', 'ix-idea-top');
  top.append(el('b', 'ix-id', it.id));
  if (it.rec) top.append(el('span', 'k-pill k-pill--xs k-pill--gold', '★ советую'));
  if (it.ask) top.append(el('span', 'k-pill k-pill--xs k-pill--special', 'реши ты'));
  top.append(costBadge(it.c));
  const w = el('span', 'ix-idea-w');
  w.append(el('b', '', 'Зачем: '), document.createTextNode(it.w));
  c.append(top, el('span', 'ix-idea-t', it.t), el('span', 'ix-idea-d', it.d), w);
  if (it.r) c.append(el('span', 'ix-idea-r', it.r));
  const take = el('span', 'ix-take');
  take.append(el('span', 'ix-check'), el('span', '', 'Беру'));
  c.append(take);
  c.addEventListener('click', () => toggle(it.id));
  addNode(it.id, c);
  return c;
}

