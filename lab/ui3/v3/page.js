const ro = new ResizeObserver((list) => { for (const e of list) fit(e.target); });
function fit(box) {
  const { x, y, w } = box.dataset;
  box.firstElementChild.style.transform = `scale(${box.clientWidth / w}) translate(${-x}px, ${-y}px)`;
}
// size — свой размер экрана сцены (телефон 844×390): iframe того же размера, иначе кнопки встанут по краям 1440×900
function frame(src, { x = 0, y = 0, w = 1440, h = 900 } = {}, { lazy = true, live = false, title = 'Экран игры', size } = {}) {
  const box = el('div', `pg-fr${live ? ' is-live' : ''}`);
  Object.assign(box.dataset, { x, y, w, h });
  box.style.aspectRatio = `${w} / ${h}`;
  const f = el('iframe');
  f.title = title;
  if (lazy) f.loading = 'lazy';
  if (!live) f.tabIndex = -1;
  f.src = src;
  if (size) Object.assign(f.style, { width: `${size[0]}px`, height: `${size[1]}px` });
  box.append(f);
  ro.observe(box);
  return box;
}
