// «Ракушка»: разовые эффекты, которые контроллер (state.ts) раздаёт видам по разнице снимков (docs/quiz/tech.md §14).
// HUD (client/lobby/quiz/ui/hud.ts, Sonnet) получает их в QuizHud.fx(e): звуки, полёт строки в «Тепло», конфетти на плашке.
// 3D (облачка, хлопки, лампочки, Затейник) делает интегратор сам — эти эффекты HUD можно игнорировать.

/** Звуки «Ракушки» (тихие, с выключателем звуков интерфейса — бриф «Как выглядит в игре → Отклик») */
export type QuizSound =
  /** новая строка «В игру» над головой */
  | 'pop'
  /** голос за карточку */
  | 'vote'
  /** 👍 «тепло» — тихий звон */
  | 'warm'
  /** 👎 «мимо» — глухой стук */
  | 'miss'
  /** «Угадал» — 3 с барабанной дроби «Проверяем…» */
  | 'drum'
  /** проверку отменили */
  | 'undo'
  /** разгадали — фанфара */
  | 'fanfare'
  /** «Не угадали» / «ушёл» — мягкое «бзз» */
  | 'fail'
  /** хлопок при переносе загадывающего на сцену и обратно */
  | 'puff'
  /** последние 3 секунды — тихий тик */
  | 'tick';

export type QuizFx =
  /** 👍: строка lineId улетает в карточку «Тепло»; from — где она была на экране (облачко автора), если видно */
  | { k: 'warmFly'; lineId: number; slot: number; from?: DOMRect | null }
  | { k: 'sound'; name: QuizSound }
  /** разгадали: конфетти у плашки (3D-конфетти из ракушки делает интегратор) */
  | { k: 'confetti' }
  /** вошёл за ограду / вышел — HUD может показать или убрать себя плавно */
  | { k: 'inside'; on: boolean }
  /** загадывающий нажал H — открыть окно «Подсказка» */
  | { k: 'hint' };
