// Высоты пола новой набережной (флаг PLAZA3): слои земли блокаута (plaza3/world.ts) и наклейки на земле (круги режимов,
// старт картинга, пятна света, тени-пятна, лужи) — так, чтобы ничто плоское не лежало вплотную к другому и не мерцало.
//
// Как было (владелец, 11.10): земля — стопка 0 / 1,2 / 3 / 4,8 / 6,6 см (пятна, дорожки, площадь, роза), а наклейки остались
// на высотах старой площади (0,7–2 см) — под дорожками и площадью. Наклейка со сдвигом глубины (polygonOffset) ниже слоя
// земли то видна, то нет: сдвиг растёт с наклоном взгляда, и граница «видно/не видно» ходит за камерой — круги под батутами,
// круги режимов, свет под фонарями мерцали и пропадали по мере подхода. Ещё модели павильонов (v1, не трогаем) кладут свою
// плитку на 1,5–4,4 см, а дорожки блокаута лежали на 3 см — плитка курзала, улицы арен и мола мерцала сквозь дорожку.
//
// Как стало: земля ниже всей плитки моделей — стопка 0…1,3 см с шагом 2 мм, наклейки — выше всего этого (на 4 см выше, чем
// на старой площади). Шаг 2 мм — это не «вплотную»: при ближней плоскости камеры 0,15 м и 24-битной глубине два слоя в 2 мм
// различимы до ~3 км с высоты глаз (разница глубины g·D/h против шага буфера D²·2⁻²⁴/near), а вся набережная — 150 м.
// Правило «зазор 1,5 см» (AGENTS §7) здесь держится между землёй и наклейками/плиткой моделей — именно там был сдвиг глубины.
import { PLAZA3 } from '../../../shared/layout.ts';
import { P3 } from '../../../shared/plaza3/layout.ts';

/** Слои земли блокаута над настилом (м): чем выше в списке, тем ниже; пятна не пересекаются между собой */
export const FLOOR_Y = {
  /** песок, газон, гравий, грунтовка */
  patch: 0.003,
  /** дорожки: аллеи под бульваром, бульвар под променадом (на перекрёстках сверху — променад) */
  secondary: 0.005,
  boulevard: 0.007,
  main: 0.009,
  /** круг площади и роза ветров в нём */
  plaza: 0.011,
  rose: 0.013,
} as const;

/** Самая низкая плитка моделей павильонов (улица арен, грунтовка огородов — 1,5 см): земля блокаута — ниже */
export const MODEL_FLOOR_MIN = 0.015;

/** Новая набережная со своей землёй (без старой статики) */
const NEW_PLAZA = PLAZA3 && !P3.legacyStatic;

/**
 * На сколько выше, чем на старой площади, лежат наклейки на земле (круги режимов, старт картинга, пятна света, тени-пятна,
 * лужи): выше роз и дорожек и выше плитки моделей (до 4,4 см у мола и Рыбного двора). На старой площади — 0, ничего не
 * меняется.
 */
export const DECAL_LIFT = NEW_PLAZA ? 0.04 : 0;
